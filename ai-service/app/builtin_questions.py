JUDGE_OPTIONS = [{"key": "T", "text": "正确"}, {"key": "F", "text": "错误"}]


def _single(qid, kp_id, difficulty, stem, options, answer, analysis, error_type, hint):
    return {
        "qid": qid,
        "kpId": kp_id,
        "difficulty": difficulty,
        "type": "SINGLE",
        "stem": stem,
        "options": [{"key": key, "text": text} for key, text in options],
        "answerKey": answer,
        "answerAliases": [],
        "analysis": analysis,
        "errorType": error_type,
        "hint": hint,
    }


def _judge(qid, kp_id, difficulty, stem, answer, analysis, error_type, hint):
    return {
        "qid": qid,
        "kpId": kp_id,
        "difficulty": difficulty,
        "type": "JUDGE",
        "stem": stem,
        "options": deepcopy(JUDGE_OPTIONS),
        "answerKey": answer,
        "answerAliases": ["对", "正确", "T"] if answer == "T" else ["错", "错误", "F"],
        "analysis": analysis,
        "errorType": error_type,
        "hint": hint,
    }


